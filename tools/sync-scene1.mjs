// Pulls scene 1 from the single-file prototype into this project.
//   npm run sync                       (reads ../prototype/src by default, i.e. when this folder sits beside prototype/ in the project files)
//   node tools/sync-scene1.mjs <path-to-prototype/src>
//
// While other work still edits prototype/src/scene1.template.html, that file stays the source of truth
// for scene 1 and this script regenerates the files below from it. Nothing here edits the prototype.
//   index.html                          the page markup (HUD, start card, darkroom and newspaper sequence)
//   src/scenes/scene1/style.css         the template's <style>
//   src/scenes/scene1/scene1.js         the template's main script as an ES module (export default start)
//   src/scenes/scene1/horses.js         horses.js as an ES module
//   public/scenes/scene1/{tex,assets}   textures as separate files, fetched by the browser and cached,
//                                       instead of 1.8 MB of base64 inside the page
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(process.argv[2] || path.join(ROOT, '../prototype/src'));
const read = f => fs.readFileSync(path.join(SRC, f), 'utf8');
const write = (f, s) => { const p = path.join(ROOT, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); console.log('wrote', f, s.length); };
const die = m => { console.error('sync-scene1: ' + m); process.exit(1); };

const T = read('scene1.template.html');
const URL_TEX = 'scenes/scene1/tex/', URL_ASSET = 'scenes/scene1/assets/';

// ---- copy textures and assets as files ----
for (const [from, to] of [['tex', URL_TEX], ['assets', URL_ASSET]]) {
  const dir = path.join(SRC, from), out = path.join(ROOT, 'public', to);
  fs.mkdirSync(out, { recursive: true });
  for (const f of fs.readdirSync(dir)) if (/\.(jpe?g|png|webp)$/i.test(f)) fs.copyFileSync(path.join(dir, f), path.join(out, f));
}
const texFile = k => {
  const f = fs.readdirSync(path.join(SRC, 'tex')).find(f => path.parse(f).name === k && /\.(jpe?g|webp|png)$/i.test(f));
  if (!f) die('no texture for __T_' + k + '__');
  return URL_TEX + f;
};
const fill = s => s
  .replace(/__T_(\w+?)__/g, (_, k) => texFile(k))
  .replace(/__PAPER2__/g, URL_ASSET + 'paper2.jpg')
  .replace(/__PAPER__/g, URL_ASSET + 'paper.jpg')
  .replace(/__SPECK__/g, URL_ASSET + 'speck.jpg')
  .replace(/__ARCHIVE__/g, URL_ASSET + 'archive-mirrored.jpg')
  .replace(/__TMEAN__/g, fs.readFileSync(path.join(SRC, 'tex/means.json'), 'utf8').trim());

// ---- split the template ----
const styleM = T.match(/<style>([\s\S]*?)<\/style>/);
if (!styleM) die('no <style> block');
const head = T.slice(0, T.indexOf('<style>'));
const fonts = (head.match(/<link[^>]+>/g) || []).join('\n');
const title = (head.match(/<title>[\s\S]*?<\/title>/) || ['<title>Casasola</title>'])[0];

const afterStyle = T.slice(T.indexOf('</style>') + 8);
const scriptAt = afterStyle.search(/<script\b/);
if (scriptAt < 0) die('no <script> after the markup');
const markup = afterStyle.slice(0, scriptAt).trim();

const scripts = [...afterStyle.slice(scriptAt).matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)];
const main = scripts.filter(m => !/src=/.test(m[1]) && !/__HORSES_JS__/.test(m[2])).sort((a, b) => b[2].length - a[2].length)[0];
if (!main) die('no main script');
for (const m of scripts) if (/src=/.test(m[1]) && !/three/.test(m[1])) die('unexpected external script ' + m[1]);

// ---- main script -> module ----
let js = main[2].trim();
const open = /^\(async \(\) => \{\s*'use strict';/;
if (!open.test(js) || !/\}\)\(\);\s*$/.test(js)) die('main script is no longer wrapped in (async () => { ... })();');
js = js.replace(open, '').replace(/\}\)\(\);\s*$/, '');
// a tool kit for zone modules: the shared shading, materials and layout helpers, read at the end of start()
const KIT = ['THREE', 'C', 'OUTLINE', 'IMG', 'tex', 'patch', 'FRAG', 'box', 'world', 'warpS', 'slopeS', 'warpP', 'HORSES', 'people', 'state', 'TIER'];
const kit = KIT.map(k => `${k}: typeof ${k} === 'undefined' ? undefined : ${k}`).join(', ');
// texture URLs become absolute at run time: CSS custom properties set from script resolve url() against
// the stylesheet that uses them (assets/), not the page, so relative paths would break there
js = fill(js).replace(/(['"`])(scenes\/scene1\/)/g, '__BASE + $1$2');
if (/[^'"`]scenes\/scene1\//.test(js.replace(/__BASE \+ ['"`]scenes\/scene1\//g, ''))) die('a texture path sits mid-string; give it its own string');
js = `// GENERATED by tools/sync-scene1.mjs from prototype/src/scene1.template.html. Edit the template, then npm run sync.
import * as THREE from 'three';
import { CasHorses } from './horses.js';

const __BASE = new URL('./', document.baseURI).href;

export default async function start() {
'use strict';
${js}
window.__casasola.kit = { ${kit} };
return window.__casasola;
}
`;
write('src/scenes/scene1/scene1.js', js);

// ---- horses ----
let horses = read('horses.js');
horses = `// GENERATED by tools/sync-scene1.mjs from prototype/src/horses.js.\nconst __root = {};\n` +
  horses.replace(/\}\)\(typeof window !== 'undefined' \? window : globalThis\);\s*$/, '})(__root);') +
  `\nexport const CasHorses = __root.CasHorses;\n`;
if (!/\(__root\);/.test(horses)) die('horses.js no longer ends the way the sync expects');
write('src/scenes/scene1/horses.js', horses);

// ---- css and page ----
write('src/scenes/scene1/style.css', '/* GENERATED by tools/sync-scene1.mjs from the template <style>. */\n' + fill(styleM[1].trim()) + '\n');
const leftover = (js + fill(markup)).match(/__(T_\w+|PAPER2?|SPECK|ARCHIVE|TMEAN|HORSES_JS)__/);
if (leftover) die('unfilled placeholder ' + leftover[0]);

write('index.html', `<!doctype html>
<!-- GENERATED by tools/sync-scene1.mjs. The markup comes from the scene 1 template. -->
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
${title}
${fonts}
</head>
<body>
${fill(markup)}
<script type="module" src="/src/main.js"></script>
</body>
</html>
`);
console.log('scene 1 synced from', SRC);
