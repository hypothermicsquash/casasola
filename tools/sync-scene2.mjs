// Pulls scene 2 (the Palacio Nacional, 1912) from the single-file prototype into this project.
//   npm run sync2        (reads ../prototype/src/scene2.src.html)
// The prototype stays the source of truth; this regenerates:
//   scene2.html                        the page markup (second page of the Vite build)
//   src/scenes/scene2/style.css        the prototype's <style>
//   src/scenes/scene2/scene2.js        the prototype's main script as an ES module, using the shared people kit
//   public/scenes/scene2/tex           the user's textures as files instead of base64
// Run npm run sync first so src/scenes/scene1/people-kit.js is the latest character kit.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(process.argv[2] || path.join(ROOT, '../prototype/src'));
const write = (f, s) => { const p = path.join(ROOT, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); console.log('wrote', f, s.length); };
const die = m => { console.error('sync-scene2: ' + m); process.exit(1); };
const T = fs.readFileSync(path.join(SRC, 'scene2.src.html'), 'utf8');

// textures: the same names build2.py inlines, copied as files
const TEX = { marble: 'marble.jpg', plaster: 'plaster_g.jpg', terra: 'terra.jpg', scallop: 'scallop.jpg', diaz1: 'diaz1.jpg', diaz2: 'diaz2.jpg', flag: 'flag.jpg', bush1: 'bush1.webp', bush2: 'bush2.webp' };
const URL_TEX = 'scenes/scene2/tex/', out = path.join(ROOT, 'public', URL_TEX);
fs.mkdirSync(out, { recursive: true });
for (const f of Object.values(TEX)) fs.copyFileSync(path.join(SRC, 'tex2', f), path.join(out, f));

const styleM = T.match(/<style>([\s\S]*?)<\/style>/); if (!styleM) die('no <style>');
const head = T.slice(0, T.indexOf('<style>'));
const links = (head.match(/<link[^>]+>/g) || []).join('\n');
const afterStyle = T.slice(T.indexOf('</style>') + 8);
const markup = afterStyle.slice(afterStyle.indexOf('<body>') + 6, afterStyle.search(/<script\b/)).trim();
const scripts = [...afterStyle.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)];
const main = scripts.filter(m => !/src=/.test(m[1]) && !/__PEOPLE_KIT__/.test(m[2])).sort((a, b) => b[2].length - a[2].length)[0];
if (!main) die('no main script');

let js = main[2].trim().replace(/^'use strict';/, '');
if (!/const LP = window\.LowPolyPeople/.test(js)) die('people kit hook moved');
js = js.replace('const LP = window.LowPolyPeople', 'const LP = LowPolyPeople');
for (const [k, f] of Object.entries(TEX)) { const tok = `'__T_${k}__'`; if (!js.includes(tok)) die('missing ' + tok); js = js.replace(tok, `'${URL_TEX}${f}'`); }
js = js.replace("if (src && src.startsWith('data:'))", "if (src && !src.startsWith('__'))");
js = `// GENERATED by tools/sync-scene2.mjs from prototype/src/scene2.src.html. Edit the prototype, then npm run sync2.
import * as THREE from 'three';
import { LowPolyPeople } from '../scene1/people-kit.js';
import './style.css';
${js}
`;
write('src/scenes/scene2/scene2.js', js);
write('src/scenes/scene2/style.css', styleM[1].trim() + '\n');
write('scene2.html', `<!doctype html>
<!-- GENERATED by tools/sync-scene2.mjs. The markup comes from prototype/src/scene2.src.html. -->
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<title>Casasola: Palacio Nacional, 1912</title>
${links}
</head>
<body>
${markup}
<script type="module" src="./src/scenes/scene2/scene2.js"></script>
</body>
</html>
`);
